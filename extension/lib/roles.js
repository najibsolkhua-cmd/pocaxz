const stemSet = (t) => new Set(tokens(t));
// Слова, которые есть в названиях многих профессий и сами по себе ничего не значат.
const GENERIC = new Set(tokens('менеджер специалист разработчик руководитель инженер аналитик ведущий старший младший главный помощник директор head lead manager'));

// Какие названия предложить к должности (и к резюме), без уже добавленных.
export function suggestTitles(position, have = [], resumeText = '') {
  const pos = stemSet(position);
  const taken = new Set([position, ...have].map((t) => (t || '').trim().toLowerCase()));
  const scores = new Map();
  for (const fam of ROLE_FAMILIES) {
    // Насколько семейство похоже на должность: лучшая доля общих слов с одним из названий.
    let best = 0;
    for (const title of fam) {
      const tt = stemSet(title);
      if (!tt.size || !pos.size) continue;
      const common = [...tt].filter((x) => pos.has(x)).length;
      const jaccard = common / new Set([...tt, ...pos]).size;
      // «SMM» ⊂ «SMM-специалист»: все слова должности есть в названии, и они не общие.
      const subset = common === pos.size && [...pos].some((x) => !GENERIC.has(x));
      best = Math.max(best, jaccard, subset ? 0.7 : 0);
    }
    const lower = (resumeText || '').toLowerCase();
    const inResume = lower ? fam.filter((t) => lower.includes(t.toLowerCase())).length : 0;
    // Семейство подходит, только если должность почти совпадает с одним из названий.
    // Резюме лишь поднимает подходящие названия выше, но не добавляет чужие профессии.
    if (best < 0.6) continue;
    const score = best + inResume * 0.15;
    for (const t of fam) {
      if (taken.has(t.toLowerCase())) continue;
      scores.set(t, Math.max(scores.get(t) || 0, score));
    }
  }
  return [...scores.entries()].sort((a, b) => b[1] - a[1]).map(([t]) => t).slice(0, 12);
}
