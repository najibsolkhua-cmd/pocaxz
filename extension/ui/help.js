const TITLES = {
  guarded: 'Сайт банка в «Защищённом режиме» — как включить поиск',
  access: 'Нет доступа к сайту — как разрешить',
  blocked: 'Сайт попросил проверку — что делать',
  download: 'Страница не открылась — что делать',
  empty: 'Вакансий не нашлось — что делать',
  error: 'Ошибка — что делать',
};

// Подсказка у источника; null, если всё хорошо.
export function scanHelp(src, st) {
  let kind = st.lastErrorKind || null;
  if (!kind && ['blocked', 'partial'].includes(st.lastStatus)) kind = 'blocked';
  if (!kind && st.lastStatus === 'failed') kind = 'error';
  if (!kind && st.lastStatus === 'empty') kind = 'empty';
  if (!kind || !HELP[kind]) return null;
  let host = '';
  try { host = new URL(src.url).hostname; } catch { /* оставим пустым */ }
  return box(`${src.id}:${kind}`, `${TITLES[kind]}?`, ...HELP[kind](host, src.platform === 'generic'), support());
}

// Общая справка в «Поиск и настройки».
export function scanHelpGuide() {
  return h('section', { class: 'dsec' }, h('h3', {}, 'Сайт не сканируется — что делать'),
    h('p', { class: 'muted small' }, 'У каждого источника после поиска написан итог. Если что-то не так, там же появится «Что делать?» с шагами именно для этой проблемы. Все случаи:'),
    ...['guarded', 'access', 'blocked', 'download', 'empty'].map((k) => box(`guide:${k}`, TITLES[k], ...HELP[k]('', true))),
    support());
}
